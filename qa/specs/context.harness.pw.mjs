import { test, expect } from '@playwright/test';

test('sections follow submitted topics, survive reload and stay separate across accounts', async ({ page }, testInfo) => {
  await page.goto('/qa/context-harness/');
  const nav = page.getByRole('navigation', { name: 'Your AIM sections' });
  await expect(nav.getByRole('button', { name: 'Wellness', exact: true })).toHaveCount(0);
  await expect(nav.getByRole('button', { name: 'Relationships', exact: true })).toHaveCount(0);
  await expect(page.locator('#aim-coach-nav')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Atmosphere', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Crystal Lab', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Other account event' }).click();
  await expect(page.locator('#nav-tab-wellness')).toHaveCount(0);
  await page.getByText('More', { exact: true }).click();
  await page.locator('#nav-tab-chat').click();
  await page.getByLabel('Tell AIM').fill('My health and sleep need attention.');
  await page.getByRole('button', { name: 'Share', exact: true }).click();
  await page.getByText('More', { exact: true }).click();
  await expect(page.locator('#nav-tab-wellness')).toBeVisible();
  await page.getByText('More', { exact: true }).click();
  await expect(page.locator('#coach-tab-health')).toBeVisible();
  await expect(page.locator('#nav-tab-chat')).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('#nav-tab-relationships')).toHaveCount(0);
  await page.getByLabel('Tell AIM').fill('I had an argument with my friend.');
  await page.getByRole('button', { name: 'Share', exact: true }).click();
  await expect(page.locator('#nav-tab-relationships')).toHaveCount(1);
  await expect(page.locator('#coach-tab-relationships')).toBeVisible();
  await expect(page.locator('#nav-tab-projects')).toHaveCount(0);
  await expect(page.locator('#coach-tab-spiritual')).toHaveCount(0);
  await page.reload();
  await page.getByText('More', { exact: true }).click();
  await expect(page.locator('#nav-tab-wellness')).toBeVisible();
  await page.getByText('More', { exact: true }).click();
  await expect(page.locator('#nav-tab-relationships')).toHaveCount(1);
  await testInfo.attach('revealed-sections', { body: await nav.screenshot(), contentType: 'image/png' });
  await page.getByRole('button', { name: 'Switch fixture account' }).click();
  await expect(page.locator('#nav-tab-wellness')).toHaveCount(0);
  await expect(page.locator('#nav-tab-relationships')).toHaveCount(0);
  await page.getByRole('button', { name: 'Switch fixture account' }).click();
  await page.getByText('More', { exact: true }).click();
  await expect(page.locator('#nav-tab-wellness')).toBeVisible();
  await page.getByText('More', { exact: true }).click();
  await page.getByLabel('Tell AIM').fill('I want to try the fractal atmosphere.');
  await page.getByRole('button', { name: 'Share', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Atmosphere', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Crystal Lab', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
